package game.conditions;

/**
 * This class represent the comparison operator
 *
 * @author yujiaming
 * @version 1.0
 */
public enum ComparisonOperator {
    /**
     * Equal operator
     */
    E,

    /**
     * Greater than or Equal operator
     */
    GE,

    /**
     * Less than or Equal operator
     */
    LE,

    /**
     * Greater Than operator
     */
    G,

    /**
     * Less Than operator
     */
    L
}
